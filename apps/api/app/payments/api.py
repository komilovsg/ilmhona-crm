def _view(p: Annotated[Principal, require("payments", "view")]) -> Principal:
    if is_instructor(p):
        raise DomainError(FORBIDDEN, section="payments", level="view")
    return p


def _change(p: Annotated[Principal, require("payments", "change")]) -> Principal:
    if is_instructor(p):
        raise DomainError(FORBIDDEN, section="payments", level="change")
    return p


View = Annotated[Principal, Depends(_view)]
Change = Annotated[Principal, Depends(_change)]


class Strict(BaseModel):
    model_config = ConfigDict(extra="forbid")


Amount = Annotated[Decimal, Field(gt=0, max_digits=12, decimal_places=2)]
Method = Literal["alif", "payvand", "наличные"]
Day = Annotated[date, Field(ge=MIN_DATE, le=MAX_DATE)]
Note = Annotated[str, StringConstraints(strip_whitespace=True, max_length=500)]


class PaymentIn(Strict):
    idempotency_key: uuid.UUID
    enrollment_id: uuid.UUID
    month_no: Annotated[int, Field(ge=1, le=36)]
    amount: Amount
    method: Method
    paid_at: Day
    note: Note | None = None


class PaymentUpdate(Strict):
    """Only the fields present change (`note: null` clears the note)."""

    month_no: Annotated[int, Field(ge=1, le=36)] | None = None
    amount: Amount | None = None
    method: Method | None = None
    paid_at: Day | None = None
    note: Note | None = None


Confirmer = aliased(AppUser)


def _select() -> Any:
    return (
        payment_joined(
            select(Payment, Student, Cohort, Course.name, Branch.name, Confirmer.full_name)
        )
        .join(Course, Course.id == Cohort.course_id)
        .join(Branch, Branch.id == Cohort.branch_id)
        .outerjoin(Confirmer, Confirmer.id == Payment.confirmed_by)
    )


def _out(
    pay: Payment, student: Student, cohort: Cohort, course: str, branch: str, confirmer: str | None
) -> dict[str, Any]:
    return {
        "id": pay.id,
        "version": pay.version,
        "enrollment_id": pay.enrollment_id,
        "student_id": student.id,
        "student_name": student.full_name,
        "phone": student.phone,
        "cohort_id": cohort.id,
        "cohort_code": cohort.code,
        "course_name": course,
        "branch_id": cohort.branch_id,
        "branch_name": branch,
        "month_no": pay.month_no,
        "amount": pay.amount,
        "method": pay.method,
        "paid_at": pay.paid_at,
        "status": pay.status,
        "confirmed_by": pay.confirmed_by,
        "confirmed_by_name": confirmer,
        "confirmed_at": pay.confirmed_at,
        "note": pay.note,
        "created_at": pay.created_at,
    }


def _snapshot(pay: Payment) -> dict[str, Any]:
    return {
        "month_no": pay.month_no,
        "amount": str(pay.amount),
        "method": pay.method,
        "paid_at": pay.paid_at,
        "status": pay.status,
        "note": pay.note,
    }


def _label(student: Student, cohort: Cohort, pay: Payment) -> str:
    return f"{student.full_name} ({cohort.code}), мес. {pay.month_no}"


async def _load(db: AsyncSession, p: Principal, payment_id: uuid.UUID) -> dict[str, Any]:
    row = (await db.execute(_select().where(Payment.id == payment_id))).first()
    if row is None:
        raise DomainError(NOT_FOUND)
    check_cohort_visible(p, row[2])
    return _out(*row)


async def _row(db: AsyncSession, p: Principal, payment_id: uuid.UUID) -> Any:
    row = (await db.execute(_select().where(Payment.id == payment_id))).first()
    if row is None:
        raise DomainError(NOT_FOUND)
    check_cohort_visible(p, row[2])
    return row


def _month_range(month: str) -> tuple[date, date]:
    start = date(int(month[:4]), int(month[5:]), 1)
    return start, (start.replace(day=28) + timedelta(days=4)).replace(day=1)


def _where(
    p: Principal,
    q: str | None,
    status: str | None,
    method: str | None,
    branch_id: uuid.UUID | None,
    month: str | None,
    cohort_id: uuid.UUID | None,
    enrollment_id: uuid.UUID | None = None,
) -> list[ColumnElement[bool]]:
    where = list(cohort_filters(p))
    if status:
        where.append(Payment.status == status)
    if method:
        where.append(Payment.method == method)
    if branch_id:
        where.append(Cohort.branch_id == branch_id)
    if cohort_id:
        where.append(Cohort.id == cohort_id)
    if enrollment_id:
        where.append(Payment.enrollment_id == enrollment_id)
    if month:
        first, after = _month_range(month)
        where.append(Payment.paid_at >= first)
        where.append(Payment.paid_at < after)
    if q and q.strip():
        like = f"%{q.strip().replace('%', r'\%').replace('_', r'\_')}%"
        where.append(
            or_(Student.full_name.ilike(like), Student.phone.ilike(like), Cohort.code.ilike(like))
        )
    return where


MonthParam = Annotated[str | None, Query(pattern=_MONTH.pattern)]


@router.get("")
async def list_payments(
    p: View,
    db: DB,
    q: str | None = None,
    status: Annotated[str | None, Query(pattern="^(ожидает|подтверждено)$")] = None,
    method: Annotated[str | None, Query(pattern="^(alif|payvand|наличные)$")] = None,
    branch_id: uuid.UUID | None = None,
    month: MonthParam = None,
    cohort_id: uuid.UUID | None = None,
    enrollment_id: uuid.UUID | None = None,
    page: Page = 1,
    page_size: PageSize = 25,
) -> dict[str, Any]:
    where = _where(p, q, status, method, branch_id, month, cohort_id, enrollment_id)
    rows = (
        await db.execute(
            _select()
            .where(*where)
            .order_by(Payment.paid_at.desc(), Payment.created_at.desc(), Payment.id)
            .limit(page_size)
            .offset((page - 1) * page_size)
        )
    ).all()
    totals = await payment_totals(db, where)
    return {
        "items": [_out(*r) for r in rows],
        "total": totals["count"],
        "summary": totals,
        "page": page,
        "page_size": page_size,
    }


