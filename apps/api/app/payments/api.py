@router.get("/by-cohort/{cohort_id}")
async def cohort_payments(cohort_id: uuid.UUID, p: View, db: DB) -> dict[str, Any]:
    """Money of every enrollment of a cohort and «оплатили X из Y» (#5)."""
    cohort = (await db.execute(select(Cohort).where(Cohort.id == cohort_id))).scalar_one_or_none()
    if cohort is None:
        raise DomainError(NOT_FOUND)
    check_cohort_visible(p, cohort)
    enrollments = (
        (await db.execute(select(Enrollment).where(Enrollment.cohort_id == cohort.id)))
        .scalars()
        .all()
    )
    money = await enrollment_money(db, [(e, cohort) for e in enrollments])
    return {
        "cohort_id": cohort.id,
        "months": cohort_months(cohort.start_date, cohort.end_date),
        "price_month": cohort.price_month,
        "enrolled": (await cohort_enrolled(db, [cohort.id]))[cohort.id],
        "payers": (await cohort_payers(db, [cohort.id]))[cohort.id],
        "items": [{"enrollment_id": e.id, **money[e.id]} for e in enrollments],
    }


@router.get("/options")
async def enrollment_options(
    p: View,
    db: DB,
    q: str | None = None,
    cohort_id: uuid.UUID | None = None,
    enrollment_id: uuid.UUID | None = None,
    limit: Annotated[int, Query(ge=1, le=50)] = 20,
) -> list[dict[str, Any]]:
    """What the payment form picks from: live enrollments (not expelled, cohort not cancelled)
    with the price, the months and what is already paid."""
    where = [*cohort_filters(p), Enrollment.status != EXPELLED, Cohort.status != "отменён"]
    if cohort_id:
        where.append(Cohort.id == cohort_id)
    if enrollment_id:
        where.append(Enrollment.id == enrollment_id)
    if q and q.strip():
        like = f"%{q.strip().replace('%', r'\%').replace('_', r'\_')}%"
        where.append(
            or_(Student.full_name.ilike(like), Student.phone.ilike(like), Cohort.code.ilike(like))
        )
    rows = (
        await db.execute(
            select(Enrollment, Cohort, Student, Course.name)
            .join(Cohort, Cohort.id == Enrollment.cohort_id)
            .join(Student, Student.id == Enrollment.student_id)
            .join(Course, Course.id == Cohort.course_id)
            .where(*where)
            .order_by(Student.full_name, Cohort.code)
            .limit(limit)
        )
    ).all()
    money = await enrollment_money(db, [(e, c) for e, c, _, _ in rows])
    out: list[dict[str, Any]] = []
    for e, c, s, course in rows:
        months = cohort_months(c.start_date, c.end_date)
        paid = set(money[e.id]["paid_months"])
        out.append(
            {
                "enrollment_id": e.id,
                "student_name": s.full_name,
                "phone": s.phone,
                "cohort_id": c.id,
                "cohort_code": c.code,
                "course_name": course,
                "price_month": c.price_month,
                "months": months,
                "next_month": next((m for m in range(1, months + 1) if m not in paid), months),
                **money[e.id],
            }
        )
    return out


