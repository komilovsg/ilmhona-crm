"""Payments (stage 2): list, create (idempotent), edit, confirm, delete, debtors, per-cohort sums.

Rights: section `payments` (view to read, change to write). The instructor role never reaches
money of students (403) and never writes. Branch scope through enrollment → cohort. Every number
(totals, paid months, debt, «оплатили») comes from `app.metrics.money`.

A payment is created «ожидает» and counts as income only after somebody confirms it. A confirmed
payment is frozen: unconfirm it first. `idempotency_key` (generated by the client) makes a retry of
the same create return the stored payment instead of a second one.
"""

