@router.patch("/{payment_id}")
async def update_payment(
    payment_id: uuid.UUID, body: PaymentUpdate, version: Version, p: Change, db: DB
) -> dict[str, Any]:
    row = await _row(db, p, payment_id)
    pay: Payment = row[0]
    await check_version(db, pay, version, "payment", lambda: _load(db, p, payment_id))
    if pay.status == CONFIRMED:
        raise DomainError(PAYMENT_CONFIRMED)
    before = _snapshot(pay)
    sent = body.model_fields_set
    if "month_no" in sent and body.month_no is not None:
        months = cohort_months(row[2].start_date, row[2].end_date)
        if body.month_no > months:
            raise DomainError(PAYMENT_MONTH_INVALID, months=months)
        pay.month_no = body.month_no
    for field in ("amount", "method", "paid_at"):
        if field in sent and getattr(body, field) is not None:
            setattr(pay, field, getattr(body, field))
    if "note" in sent:
        pay.note = body.note or None
    await db.flush()
    await db.refresh(pay)  # amounts as the database stores them (550 -> 550.00)
    await record(
        db,
        p.id,
        "payment.update",
        "payment",
        pay.id,
        diff_of(before, _snapshot(pay)),
        branch_id=row[2].branch_id,
        label=_label(row[1], row[2], pay),
    )
    return await _load(db, p, payment_id)


async def _set_status(
    db: AsyncSession, p: Principal, payment_id: uuid.UUID, version: int, status: str, action: str
) -> dict[str, Any]:
    """Confirming is a decision on the payment as the confirmer saw it: an edit made meanwhile is
    a 409 (#25). The row lock makes two people confirming at once see each other."""
    row = await _row(db, p, payment_id)
    pay: Payment = row[0]
    await check_version(db, pay, version, "payment", lambda: _load(db, p, payment_id))
    if pay.status != status:
        pay.status = status
        pay.confirmed_by = p.id if status == CONFIRMED else None
        pay.confirmed_at = datetime.now(UTC) if status == CONFIRMED else None
        await db.flush()
        await record(
            db,
            p.id,
            action,
            "payment",
            pay.id,
            {"status": [PENDING if status == CONFIRMED else CONFIRMED, status]},
            branch_id=row[2].branch_id,
            label=_label(row[1], row[2], pay),
        )
    return await _load(db, p, payment_id)


