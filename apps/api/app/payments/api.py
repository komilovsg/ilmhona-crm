@router.delete("/{payment_id}", status_code=204)
async def delete_payment(payment_id: uuid.UUID, p: Change, db: DB) -> None:
    row = await _row(db, p, payment_id)
    pay: Payment = row[0]
    await lock(db, pay)
    if pay.status == CONFIRMED:
        raise DomainError(PAYMENT_CONFIRMED)
