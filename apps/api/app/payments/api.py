def _debtor_select(
    p: Principal, q: str | None, branch_id: uuid.UUID | None, cohort_id: uuid.UUID | None
) -> Any:
    where = [*cohort_filters(p), Enrollment.status != EXPELLED, Cohort.status != "отменён"]
    if branch_id:
        where.append(Cohort.branch_id == branch_id)
    if cohort_id:
        where.append(Cohort.id == cohort_id)
    if q and q.strip():
        like = f"%{q.strip().replace('%', r'\%').replace('_', r'\_')}%"
        where.append(
            or_(Student.full_name.ilike(like), Student.phone.ilike(like), Cohort.code.ilike(like))
        )
    return (
        select(Enrollment, Cohort, Student, Course.name, Branch.name)
        .join(Cohort, Cohort.id == Enrollment.cohort_id)
        .join(Student, Student.id == Enrollment.student_id)
        .join(Course, Course.id == Cohort.course_id)
        .join(Branch, Branch.id == Cohort.branch_id)
        .where(*where)
    )


async def _debtors(
    db: AsyncSession,
    p: Principal,
    q: str | None,
    branch_id: uuid.UUID | None,
    cohort_id: uuid.UUID | None,
) -> list[dict[str, Any]]:
    rows = (await db.execute(_debtor_select(p, q, branch_id, cohort_id))).all()
    money = await enrollment_money(db, [(e, c) for e, c, _, _, _ in rows])
    out = [
        {
            "enrollment_id": e.id,
            "student_id": s.id,
            "student_name": s.full_name,
            "phone": s.phone,
            "cohort_id": c.id,
            "cohort_code": c.code,
            "course_name": course,
            "branch_name": branch,
            "price_month": c.price_month,
            "months": cohort_months(c.start_date, c.end_date),
            **money[e.id],
        }
        for e, c, s, course, branch in rows
        if money[e.id]["debt"] > 0
    ]
    out.sort(key=lambda r: (-r["debt"], r["student_name"], str(r["enrollment_id"])))
    return out


